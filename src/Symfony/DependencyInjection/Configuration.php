<?php

declare(strict_types=1);

namespace OpsFour\S3Server\Symfony\DependencyInjection;

use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

final class Configuration implements ConfigurationInterface
{
    /** @return TreeBuilder<'array'> */
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('opsfour_s3_server');

        $treeBuilder->getRootNode()
            ->children()
                ->arrayNode('server')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('host')->defaultValue('0.0.0.0')->end()
                        ->integerNode('port')->defaultValue(9000)->min(1)->max(65535)->end()
                        ->scalarNode('region')->defaultValue('us-east-1')->end()
                        ->scalarNode('cluster_id')->defaultNull()->end()
                        ->scalarNode('cluster_node_id')->defaultNull()->end()
                        ->scalarNode('cluster_database_id')->defaultNull()->end()
                        ->variableNode('cluster_roles')->defaultNull()->end()
                        ->variableNode('cluster_required_roles')->defaultNull()->end()
                        ->scalarNode('tls_cert_path')->defaultNull()->end()
                        ->scalarNode('tls_key_path')->defaultNull()->end()
                        ->integerNode('max_connections')->defaultValue(10000)->min(1)->end()
                        ->integerNode('connection_idle_timeout')->defaultValue(60)->min(0)->end()
                        ->integerNode('body_size_limit')->defaultValue(5_368_709_120)->min(0)->end()
                        ->integerNode('post_spool_budget')->defaultNull()->min(1)->end()
                        ->floatNode('local_write_worker_timeout_seconds')->defaultValue(300.0)->min(0.001)->end()
                        ->integerNode('read_timeout')->defaultValue(300)->min(0)->end()
                        ->integerNode('write_timeout')->defaultValue(300)->min(0)->end()
                        ->integerNode('rate_limit')->defaultValue(1000)->min(0)->end()
                        ->arrayNode('trusted_proxy_cidrs')->scalarPrototype()->end()->defaultValue([])->end()
                        ->scalarNode('base_domain')->defaultNull()->end()
                        ->booleanNode('strict_bucket_naming')->defaultTrue()->end()
                        ->scalarNode('website_host_pattern')->defaultNull()->end()
                        ->scalarNode('master_key_provider')->defaultNull()->end()
                        ->booleanNode('enforce_min_part_size')->defaultTrue()->end()
                        ->integerNode('max_encrypted_object_size')->defaultValue(268_435_456)->min(1)->end()
                        ->integerNode('max_select_object_size')->defaultValue(67_108_864)->min(1)->end()
                        ->integerNode('shutdown_drain_timeout')->defaultValue(30)->min(1)->end()
                        ->integerNode('shutdown_readiness_delay')->defaultValue(5)->min(0)->max(300)->end()
                        ->booleanNode('allow_unfenced_storage_for_tests')->defaultFalse()->end()
                        ->scalarNode('metrics_bearer_token')->defaultNull()->end()
                    ->end()
                ->end()
                ->arrayNode('storage')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('driver')->values(['filesystem', 'flysystem', 'aws-s3', 'memory'])->defaultValue('filesystem')->end()
                        ->scalarNode('path')->defaultValue('/tmp/opsfour-s3-server')->end()
                        ->scalarNode('tier')->defaultValue('STANDARD')->end()
                        ->scalarNode('temp_dir')->defaultValue('/tmp/opsfour-s3-server-temp')->end()
                        ->integerNode('temp_budget_bytes')->defaultValue(10_737_418_240)->min(1)->end()
                        ->integerNode('temp_reserve_bytes')->defaultValue(1_073_741_824)->min(0)->end()
                        ->integerNode('worker_pool_size')->defaultValue(0)->min(0)->end()
                        ->integerNode('read_first_byte_timeout_seconds')->defaultValue(20)->min(1)->end()
                        ->scalarNode('filesystem_service')->defaultNull()->end()
                        ->scalarNode('filesystem_factory_service')->defaultNull()->end()
                        ->variableNode('filesystem')->defaultNull()->end()
                        ->variableNode('filesystem_factory')->defaultNull()->end()
                        ->scalarNode('bucket')->defaultNull()->end()
                        ->scalarNode('region')->defaultNull()->end()
                        ->scalarNode('expected_owner_id')->defaultNull()->end()
                        ->scalarNode('data_prefix')->defaultNull()->end()
                        ->scalarNode('reserved_prefix')->defaultNull()->end()
                        ->integerNode('connect_timeout_seconds')->defaultValue(5)->min(1)->max(30)->end()
                        ->integerNode('read_timeout_seconds')->defaultValue(15)->min(1)->max(120)->end()
                        ->integerNode('request_timeout_seconds')->defaultValue(20)->min(1)->max(120)->end()
                        ->arrayNode('tiers')
                            ->useAttributeAsKey('name')
                            ->arrayPrototype()
                                ->children()
                                    ->enumNode('driver')->values(['filesystem', 'flysystem', 'aws-s3', 'memory'])->defaultValue('filesystem')->end()
                                    ->scalarNode('path')->defaultNull()->end()
                                    ->booleanNode('restore_required')->defaultFalse()->end()
                                    ->booleanNode('default')->defaultFalse()->end()
                                    ->scalarNode('temp_dir')->end()
                                    ->integerNode('temp_budget_bytes')->min(1)->end()
                                    ->integerNode('temp_reserve_bytes')->min(0)->end()
                                    ->integerNode('worker_pool_size')->defaultValue(0)->min(0)->end()
                                    ->integerNode('read_first_byte_timeout_seconds')->min(1)->end()
                                    ->scalarNode('filesystem_service')->defaultNull()->end()
                                    ->scalarNode('filesystem_factory_service')->defaultNull()->end()
                                    ->variableNode('filesystem')->defaultNull()->end()
                                    ->variableNode('filesystem_factory')->defaultNull()->end()
                                    ->scalarNode('bucket')->defaultNull()->end()
                                    ->scalarNode('region')->defaultNull()->end()
                                    ->scalarNode('expected_owner_id')->defaultNull()->end()
                                    ->scalarNode('data_prefix')->defaultNull()->end()
                                    ->scalarNode('reserved_prefix')->defaultNull()->end()
                                    ->integerNode('connect_timeout_seconds')->defaultValue(5)->min(1)->max(30)->end()
                                    ->integerNode('read_timeout_seconds')->defaultValue(15)->min(1)->max(120)->end()
                                    ->integerNode('request_timeout_seconds')->defaultValue(20)->min(1)->max(120)->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('metadata')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('driver')->values(['sqlite', 'postgres', 'mysql'])->defaultValue('sqlite')->end()
                        ->scalarNode('dsn')->defaultValue('')->end()
                        ->scalarNode('path')->defaultNull()->end()
                        ->floatNode('cache_ttl')->defaultValue(5.0)->min(0)->end()
                    ->end()
                ->end()
                ->arrayNode('credentials')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('driver')->values(['memory', 'database', 'file'])->defaultValue('memory')->end()
                        ->scalarNode('access_key')->defaultNull()->end()
                        ->scalarNode('secret_key')->defaultNull()->end()
                        ->scalarNode('owner_id')->defaultNull()->end()
                        ->scalarNode('display_name')->defaultNull()->end()
                        ->scalarNode('dsn')->defaultNull()->end()
                        ->scalarNode('username')->defaultNull()->end()
                        ->scalarNode('password')->defaultNull()->end()
                        ->floatNode('cache_ttl')->defaultValue(1.0)->min(0)->end()
                        ->floatNode('operation_timeout_seconds')->defaultValue(15.0)->min(0.001)->end()
                        ->scalarNode('path')->defaultNull()->end()
                    ->end()
                ->end()
                ->arrayNode('admin')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('token')->defaultNull()->end()
                    ->end()
                ->end()
                ->arrayNode('external_iam')
                    ->normalizeKeys(false)
                    ->variablePrototype()->end()
                ->end()
                ->arrayNode('parallel')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('sqlite_workers')->defaultValue(4)->min(0)->end()
                        ->integerNode('credential_workers')->defaultValue(4)->min(0)->end()
                        ->integerNode('encryption_workers')->defaultValue(0)->min(0)->end()
                        ->integerNode('select_workers')->defaultValue(1)->min(0)->end()
                        ->integerNode('request_body_spool_workers')->defaultValue(8)->min(1)->end()
                        ->integerNode('encryption_threshold')->defaultValue(65_536)->min(0)->end()
                    ->end()
                ->end()
                ->arrayNode('quotas')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('max_buckets_per_owner')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_objects_per_bucket')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_bytes_per_bucket')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_bytes_per_owner')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_multipart_uploads_per_bucket')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_multipart_uploads_per_owner')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_multipart_bytes_per_bucket')->defaultValue(0)->min(0)->end()
                        ->integerNode('max_multipart_bytes_per_owner')->defaultValue(0)->min(0)->end()
                    ->end()
                ->end()
                ->arrayNode('lifecycle')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->floatNode('interval_seconds')->defaultValue(60.0)->min(0.001)->end()
                        ->integerNode('batch_size')->defaultValue(1000)->min(1)->end()
                        ->integerNode('max_actions_per_run')->defaultValue(1000)->min(1)->end()
                        ->integerNode('lock_ttl_seconds')->defaultValue(300)->min(1)->end()
                        ->integerNode('multipart_max_age_seconds')->defaultValue(604_800)->min(0)->end()
                    ->end()
                ->end()
                ->arrayNode('notifications')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('require_https')->defaultTrue()->end()
                        ->booleanNode('worker_enabled')->defaultTrue()->end()
                        ->arrayNode('symfony_event_dispatcher')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->scalarNode('service')->defaultNull()->end()
                                ->scalarNode('pattern')->defaultValue('s3:*')->end()
                                ->scalarNode('event_name')->defaultNull()->end()
                            ->end()
                        ->end()
                        ->arrayNode('listeners')
                            ->arrayPrototype()
                                ->children()
                                    ->scalarNode('event')->isRequired()->cannotBeEmpty()->end()
                                    ->scalarNode('service')->isRequired()->cannotBeEmpty()->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('encryption')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('service')->defaultNull()->end()
                        ->scalarNode('master_key_provider_service')->defaultNull()->end()
                    ->end()
                ->end()
            ->end();

        return $treeBuilder;
    }
}
